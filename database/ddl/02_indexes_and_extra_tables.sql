CREATE TABLE vaccinations (
    vaccination_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livestock_id   NUMBER NOT NULL,
    vaccine_name   VARCHAR2(100) NOT NULL,
    dose_ml        NUMBER(6,2) NOT NULL CHECK (dose_ml > 0),
    date_given     DATE DEFAULT SYSDATE NOT NULL,
    next_due_date  DATE,
    administered_by VARCHAR2(120),
    CONSTRAINT fk_vacc_livestock FOREIGN KEY (livestock_id)
        REFERENCES livestock (livestock_id)
) TABLESPACE smartherd_data;

CREATE TABLE milk_production (
    production_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livestock_id   NUMBER NOT NULL,
    milking_date   DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    morning_liters NUMBER(6,2) DEFAULT 0 CHECK (morning_liters >= 0),
    evening_liters NUMBER(6,2) DEFAULT 0 CHECK (evening_liters >= 0),
    quality_grade  VARCHAR2(20) DEFAULT 'GRADE_A' CHECK (quality_grade IN ('GRADE_A', 'GRADE_B', 'REJECTED')),
    CONSTRAINT fk_milk_livestock FOREIGN KEY (livestock_id)
        REFERENCES livestock (livestock_id),
    CONSTRAINT uq_livestock_milk_date UNIQUE (livestock_id, milking_date)
) TABLESPACE smartherd_data;

-- Indexes in SMARTHERD_IDX for query performance
CREATE INDEX idx_livestock_farm ON livestock (farm_id) TABLESPACE smartherd_idx;
CREATE INDEX idx_livestock_status ON livestock (health_status) TABLESPACE smartherd_idx;
CREATE INDEX idx_vet_livestock ON vet_records (livestock_id) TABLESPACE smartherd_idx;
CREATE INDEX idx_vacc_livestock ON vaccinations (livestock_id) TABLESPACE smartherd_idx;
CREATE INDEX idx_milk_date ON milk_production (milking_date) TABLESPACE smartherd_idx;
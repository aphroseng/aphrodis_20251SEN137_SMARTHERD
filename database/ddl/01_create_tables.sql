CREATE TABLE farms (
    farm_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_name      VARCHAR2(120) NOT NULL,
    location       VARCHAR2(150) NOT NULL,
    owner_name     VARCHAR2(120),
    created_at     DATE DEFAULT SYSDATE NOT NULL
) TABLESPACE smartherd_data;

CREATE TABLE livestock (
    livestock_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id        NUMBER NOT NULL,
    tag_code       VARCHAR2(50) NOT NULL UNIQUE,
    species        VARCHAR2(50) NOT NULL,
    breed          VARCHAR2(80),
    birth_date     DATE,
    gender         VARCHAR2(10) CHECK (gender IN ('MALE', 'FEMALE')),
    health_status  VARCHAR2(30) DEFAULT 'HEALTHY' CHECK (health_status IN ('HEALTHY', 'SICK', 'QUARANTINE', 'TREATED')),
    registered_at  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_livestock_farm FOREIGN KEY (farm_id)
        REFERENCES farms (farm_id)
) TABLESPACE smartherd_data;

CREATE TABLE vet_records (
    record_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livestock_id   NUMBER NOT NULL,
    visit_date     DATE DEFAULT SYSDATE NOT NULL,
    diagnosis      VARCHAR2(250) NOT NULL,
    treatment      VARCHAR2(250),
    vet_name       VARCHAR2(120),
    next_checkup   DATE,
    CONSTRAINT fk_vet_livestock FOREIGN KEY (livestock_id)
        REFERENCES livestock (livestock_id)
) TABLESPACE smartherd_data;
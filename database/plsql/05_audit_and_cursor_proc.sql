CREATE OR REPLACE PROCEDURE prc_print_farm_herd_report (
    p_farm_id IN farms.farm_id%TYPE
) IS
    CURSOR c_herd IS
        SELECT tag_code, species, breed, health_status, total_milk_liters
          FROM vw_herd_health_milk_summary
         WHERE farm_id = p_farm_id
         ORDER BY tag_code;

    v_found BOOLEAN := FALSE;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== SMARTHERD FARM REPORT (FARM ID: ' || p_farm_id || ') ===');

    FOR r IN c_herd LOOP
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(
            'Tag: ' || r.tag_code ||
            ' | ' || r.species || ' (' || NVL(r.breed, 'N/A') || ')' ||
            ' | Status: ' || r.health_status ||
            ' | Total Milk: ' || r.total_milk_liters || ' L'
        );
    END LOOP;

    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('No livestock found for farm_id = ' || p_farm_id);
    END IF;
END prc_print_farm_herd_report;

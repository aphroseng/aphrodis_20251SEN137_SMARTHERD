CREATE TABLE audit_log (
    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name     VARCHAR2(50) NOT NULL,
    record_id      NUMBER NOT NULL,
    old_status     VARCHAR2(30),
    new_status     VARCHAR2(30),
    changed_by     VARCHAR2(100) DEFAULT USER NOT NULL,
    changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE smartherd_data;

CREATE OR REPLACE TRIGGER trg_audit_livestock_status
AFTER UPDATE OF health_status ON livestock
FOR EACH ROW
WHEN (NVL(OLD.health_status, 'X') <> NVL(NEW.health_status, 'X'))
BEGIN
    INSERT INTO audit_log (
        table_name, record_id, old_status, new_status
    ) VALUES (
        'LIVESTOCK', :NEW.livestock_id, :OLD.health_status, :NEW.health_status
    );
END;
